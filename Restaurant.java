public class Restaurant
{
    private String name;
    private int sitzplaetze;
    private boolean vegetarisch;
    
    public String getName()
    {
        return name;
    }
    
    public int getSitzplaetze()
    {
        return sitzplaetze;
    }
    
    public boolean getVegetarisch()
    {
        return vegetarisch;
    }
}